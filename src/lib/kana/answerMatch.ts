// 단어장 정답 비교용 정규화.
//
// 이 앱에서 한자 입력은 필기 인식(kanjicanvas), 히라가나 입력은 버튼 팔레트로만 이뤄진다.
// 그런데 단어장 CSV의 kanji 컬럼에는 가타카나·영문·숫자·문장부호처럼 어느 쪽으로도 입력할
// 수 없는 문자가 섞여 있을 수 있고(예: 외래어), 그런 문자가 하나라도 있으면 정답을 영원히
// 못 맞히게 된다. 그래서 채점 비교 시에는 실제로 입력 가능한 글자(히라가나 + 한자)만 남기고
// 나머지(입력 불가능한 문자, 공백)는 제외한다 — 공백은 입력 가능(버튼도 있음)하지만 사람마다
// 띄어쓰는 위치가 다를 수 있어 어차피 판정에서 의미가 없으므로 마찬가지로 제외한다.
// 히라가나(U+3041–3096, 반복부호 U+309D–309F) + 한자(CJK 통합 U+4E00–9FFF, 확장 A U+3400–4DBF).
const COMPARABLE_CHAR = /[ぁ-ゖゝ-ゟ一-鿿㐀-䶿]/;

/** 정답 비교 직전에 양쪽(입력값/정답)에 똑같이 적용한다. */
export function normalizeForMatch(text: string): string {
  return Array.from(text)
    .filter((ch) => COMPARABLE_CHAR.test(ch))
    .join('');
}
